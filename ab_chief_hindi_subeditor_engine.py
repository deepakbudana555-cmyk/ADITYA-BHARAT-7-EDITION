def clean_and_transliterate_hindi(raw_text: str) -> str:
    """Strips English prefix labels, transliterates known acronyms to Devanagari, and removes date fillers."""
    if not raw_text:
        return ""
    s = html.unescape(raw_text).strip()
    # Normalize zero-width joiners
    s = s.replace("\u200d", "").replace("\u200c", "")
    # Strip trailing publisher after ' - ' or ' | '
    s = re.split(r"\s+[-|–—]\s+", s)[0].strip()
    # If there is an English prefix before ':' (e.g. 'Rajasthan Panchayat Election Result: ...' or 'IND vs NZ 1st: ...'), strip it
    if ":" in s:
        first_seg, rest_seg = s.split(":", 1)
        if len(re.findall(r"[A-Za-z]", first_seg)) >= 3 and len(re.findall(r"[\u0900-\u097F]", rest_seg)) >= 12:
            s = rest_seg.strip()
    # Transliterate known English acronyms to Hindi
    for eng, hin in sorted(ACRONYM_TO_HINDI.items(), key=lambda kv: -len(kv[0])):
        s = re.sub(rf"\b{re.escape(eng)}\b", hin, s, flags=re.IGNORECASE)
    # Remove whole date/day adverbial filler phrases ('20 नवंबर को', 'शुक्रवार को', 'आज')
    s = re.sub(r"\b\d{1,2}\s+(?:जनवरी|फरवरी|मार्च|अप्रैल|मई|जून|जुलाई|अगस्त|सितंबर|अक्टूबर|नवंबर|दिसंबर)\s+को\b", " ", s)
    s = re.sub(r"\b(?:सोमवार|मंगलवार|बुधवार|गुरुवार|शुक्रवार|शनिवार|रविवार)\s+को\b", " ", s)
    return s.strip()


def extract_intact_natural_hindi_headline(
    raw_title: str,
    min_words: int = 5,
    max_words: int = 8,
    min_chars: int = 22,
    max_chars: int = 56,
) -> str:
    """
    Extracts an UNTOUCHED, 100% grammatical Hindi clause from `raw_title` without ever
    deleting middle words or gluing fake suffixes.
    Returns '' if no intact clause in `raw_title` meets strict newspaper grammar standards.
    """
    s = clean_and_transliterate_hindi(raw_title)
    if not s:
        return ""
    # Split into natural clauses at ':', ';', ',', '।', '!', '?', '...'
    raw_clauses = [c.strip(" :;,-।\"'“”‘’!?…") for c in re.split(r"[:;।,!?]|\.{2,}", s) if c.strip(" :;,-।\"'“”‘’!?…")]

    for cl in raw_clauses:
        # Reject clause if it still contains Latin letters, decimal numbers, or currency/weird symbols
        if re.search(r"[A-Za-z0-9₹$%@#&_=+~`|\\/<>]", cl):
            continue
        cl_clean = re.sub(r"[\"'“”‘’`\[\]\(\)•…?!]", " ", cl)
        cl_clean = re.sub(r"\s+", " ", cl_clean).strip(" :;,-।.")
        words = cl_clean.split()
        if not words:
            continue
        # Drop trailing auxiliary 'है'/'हैं' only if preceded by a complete participle in NATURAL_HEADLINE_ENDINGS
        if len(words) >= 6 and words[-1] in {"है", "हैं"} and words[-2] in NATURAL_HEADLINE_ENDINGS:
            words = words[:-1]
        if not (min_words <= len(words) <= max_words):
            continue
        if any(w in REJECT_CLAUSE_TOKENS for w in words):
            continue
        if words[0] in {"ने", "का", "की", "के", "को", "में", "से", "पर", "और", "व", "कि", "तो", "है", "हैं"}:
            continue
        last_w = words[-1].rstrip("।.")
        if last_w in INVALID_FINAL_WORDS:
            continue
        if last_w not in NATURAL_HEADLINE_ENDINGS:
            continue
        cand = " ".join(words)
        if min_chars <= len(cand) <= max_chars:
            return cand
    return ""


