def _atomic_story(
    headline: str,
    subhead: str,
    city: str,
    agency: str,
    blurb: str,
    lead_para: str,
    detail_para: str,
    bullets: list[str] = None,
    photo: str = "",
    caption: str = "",
    kicker: str = "",
    box_head: str = "प्रमुख बिंदु",
) -> dict:
    """Constructs a 100% cohesive, single-source atomic newspaper story dictionary."""
    full_body = f"{lead_para.strip()}\n{detail_para.strip()}"
    if bullets:
        box_bullets = "\n".join(f"• {b.strip('• ')}" for b in bullets)
    else:
        box_bullets = (
            f"• {subhead.split(':')[0].strip()} के तहत चरणबद्ध क्रियान्वयन शुरू।\n"
            f"• {city} सहित संबंधित क्षेत्रों में आधुनिक बुनियादी ढांचे व सुविधाओं का विस्तार।\n"
            "• विभागीय निगरानी पोर्टल के माध्यम से हितग्राहियों को मिलेगा सीधा और पारदर्शी लाभ।"
        )
    out = {
        "headline": headline.strip(),
        "subhead": subhead.strip(),
        "kicker": (kicker or subhead).strip(),
        "city": city.strip(),
        "agency": agency.strip(),
        "blurb": blurb.strip(),
        "box_title": box_head,
        "box_head": box_head,
        "box_bullets": box_bullets,
        "body": full_body,
    }
    if photo:
        out["photo"] = photo
    if caption:
        out["caption"] = caption
    return out


