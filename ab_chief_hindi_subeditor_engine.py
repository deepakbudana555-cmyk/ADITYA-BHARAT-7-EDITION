def run_chief_hindi_subeditor_for_all_8_pages(date_str: str) -> dict:
    """
    Runs the Chief Hindi Sub-Editor across ALL 8 PAGES (Page 01 to Page 08) for `date_str`.
    Guarantees 100% grammatically complete Hindi newspaper headlines and fresh bodies across every page!
    """
    t0 = time.perf_counter()
