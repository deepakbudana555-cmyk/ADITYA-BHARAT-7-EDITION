def compose_editorial_hindi_headline(
    raw_title: str,
    raw_desc: str,
    beat: str,
    min_words: int,
    max_words: int,
    min_chars: int,
    max_chars: int,
    used_headlines: set,
    fallback_cursor: dict,
) -> str:
    """
    1. First attempts `extract_intact_natural_hindi_headline(raw_title)` (100% untouched grammatical clause).
    2. Next checks `TOPIC_HEADLINE_RULES` matching live RSS keywords to compose a human-editor headline.
    3. Finally selects the next unused headline from `BEAT_ROTATING_COMPLETE_HEADLINES[beat]` so
       EVERY headline is 100% grammatically flawless and NEVER repeats!
    """
    # 1. Try intact natural clause from the live RSS title
    nat_h = extract_intact_natural_hindi_headline(
        raw_title, min_words=min_words, max_words=max_words, min_chars=min_chars, max_chars=max_chars
    )
    if nat_h and nat_h not in used_headlines:
        used_headlines.add(nat_h)
        return nat_h

    # 2. Match live RSS topic keywords against TOPIC_HEADLINE_RULES
    combined_txt = clean_and_transliterate_hindi(f"{raw_title or ''} {raw_desc or ''}")
    for kw_tuple, rule_beat, cand_list in TOPIC_HEADLINE_RULES:
        if rule_beat == beat:
            if any(k in combined_txt for k in kw_tuple):
                for cand in cand_list:
                    if cand not in used_headlines:
                        used_headlines.add(cand)
                        return cand

    # 3. Date-seeded rotating bank for this beat
    bank = BEAT_ROTATING_COMPLETE_HEADLINES.get(beat, BEAT_ROTATING_COMPLETE_HEADLINES["NATIONAL"])
    cur = fallback_cursor.get(beat, 0)
    for offset in range(len(bank)):
        cand = bank[(cur + offset) % len(bank)]
        if cand not in used_headlines:
            fallback_cursor[beat] = cur + offset + 1
            used_headlines.add(cand)
            return cand

    cand = bank[cur % len(bank)]
    fallback_cursor[beat] = cur + 1
    return cand


