def load_history() -> dict:
    if HISTORY_PATH.exists():
        try:
            return json.loads(HISTORY_PATH.read_text(encoding="utf-8"))
        except Exception:
            pass
    return {"used_by_date": {}, "used_package_ids": []}


def save_history(hist: dict) -> None:
    HISTORY_PATH.write_text(json.dumps(hist, ensure_ascii=False, indent=2), encoding="utf-8")


def build_daily_sampadakiya_page4(
    date_str: str = "19-11-2026",
    edition_code: str = "RAIPUR",
    force_next_series: bool = False,
) -> dict:
    edition_code = (edition_code or "RAIPUR").strip().upper()
    hist = load_history()

    live_topics = harvest_live_editorial_topics()

    # Select package for date (or advance to next series if force_next_series=True)
    used_ids = hist.get("used_package_ids", [])
    if not force_next_series and date_str in hist.get("used_by_date", {}):
        chosen_id = hist["used_by_date"][date_str]
        pkg = next((p for p in DAILY_P4_PACKAGES if p["package_id"] == chosen_id), DAILY_P4_PACKAGES[0])
    else:
        avail = [p for p in DAILY_P4_PACKAGES if p["package_id"] not in used_ids]
        if not avail:
            avail = DAILY_P4_PACKAGES
            used_ids = []
        pkg = avail[0]
        if pkg["package_id"] not in used_ids:
            used_ids.append(pkg["package_id"])
        hist.setdefault("used_by_date", {})[date_str] = pkg["package_id"]
        hist["used_package_ids"] = used_ids
        save_history(hist)

    out_json_path = CACHE_DIR / f"{date_str}_SAMPADAKIYA_PAGE4_ARTICLES.json"
    payload = dict(pkg)
    payload["date_str"] = date_str
    payload["edition_code"] = edition_code
    payload["live_rss_topics"] = live_topics
    out_json_path.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")

    env = os.environ.copy()
    env["AB_EDITION"] = edition_code
    env["AB_EDITION_DATE"] = date_str
    env["AB_P4_JSON_PATH"] = str(out_json_path)

    builder_script = VAULT_DIR / "build_aditya_bharat_page5_edit.py"
    proc = subprocess.run(
        [sys.executable, str(builder_script)],
        cwd=str(VAULT_DIR),
        env=env,
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
    )
    if proc.returncode != 0:
        raise RuntimeError(f"Page 04 build failed:\n{proc.stdout}\n{proc.stderr}")

    vault_pdf = VAULT_DIR / "Aditya_Bharat_Page_04_Sampadakiya_CMYK_34x53.pdf"
    vault_png = VAULT_DIR / "Aditya_Bharat_Page_04_Sampadakiya_34x53.png"
    vault_pd = VAULT_DIR / "Aditya_Bharat_Page_04_Sampadakiya_34x53.pagedesigner"

    desktop_pdf = DESKTOP_DIR / f"Aditya_Bharat_{edition_code.title()}_Page_04_Sampadakiya_{date_str}.pdf"
    desktop_main_pdf = DESKTOP_DIR / f"Aditya_Bharat_Sampadakiya_Page_04_{date_str}.pdf"
    if vault_pdf.exists():
        shutil.copy2(vault_pdf, desktop_pdf)
        shutil.copy2(vault_pdf, desktop_main_pdf)

    return {
        "ok": True,
        "date_str": date_str,
        "edition_code": edition_code,
        "package_id": pkg["package_id"],
        "edit1_head": pkg["edit1_head"].replace("\n", " "),
        "lead_headline": pkg["lead_headline"].replace("\n", " "),
        "mid_left_headline": pkg["mid_left_headline"].replace("\n", " "),
        "mid_right_headline": pkg["mid_right_headline"].replace("\n", " "),
        "json_path": str(out_json_path),
        "pagedesigner_path": str(vault_pd),
        "png_path": str(vault_png),
        "desktop_pdf": str(desktop_main_pdf),
        "edition_desktop_pdf": str(desktop_pdf),
        "stdout": proc.stdout.strip(),
    }


if __name__ == "__main__":
    d_arg = sys.argv[1] if len(sys.argv) > 1 else os.environ.get("AB_EDITION_DATE", "19-11-2026")
    ed_arg = sys.argv[2] if len(sys.argv) > 2 else os.environ.get("AB_EDITION", "RAIPUR")
    res = build_daily_sampadakiya_page4(date_str=d_arg, edition_code=ed_arg)
    print(json.dumps(res, ensure_ascii=False, indent=2))
